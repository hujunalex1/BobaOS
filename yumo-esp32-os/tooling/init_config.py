"""Initialize a private deployment once. Re-running preserves all existing keys."""
from pathlib import Path
import argparse, json, re, secrets, sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]

def initialize(root=ROOT, url=None):
    root = Path(root).resolve()
    identity = root/'server/deployment/local-keys.json'
    configs = [root/'firmware/vault-sync-key.properties', root/'server/vault-sync-key.properties']
    if url is not None:
        origin = urlsplit(url)
        if (origin.scheme not in ('http', 'https') or not origin.hostname or origin.username or
                origin.password or origin.path not in ('', '/') or origin.query or origin.fragment):
            raise ValueError('Use an HTTP(S) server origin, for example https://vault.example.com')
        if origin.port is not None and not 1 <= origin.port <= 65535:
            raise ValueError('Invalid port')
        url = url.rstrip('/')
    # Validate all existing files before writing anything. Never silently rotate a half-set deployment.
    have = [identity.is_file(), *(p.is_file() for p in configs)]
    if any(have) and not all(have):
        raise RuntimeError('Incomplete deployment configuration; restore matching files before initialization.')
    if all(have):
        data = json.loads(identity.read_text(encoding='utf-8'))
        if data.get('schema') != 2:
            raise ValueError('Invalid identity schema')
        for field, count in [('key',64), ('token',64), ('vault_id',32), ('salt',32)]:
            if not re.fullmatch('[0-9a-fA-F]{'+str(count)+'}', str(data.get(field,''))):
                raise ValueError('Invalid deployment identity')
        values = []
        for path in configs:
            lines = [s.strip() for s in path.read_text(encoding='utf-8').splitlines()
                     if s.strip() and not s.lstrip().startswith('#')]
            match = re.fullmatch(r'sync\.key\.hex\s*=\s*([0-9a-fA-F]{64})', lines[0]) if len(lines)==1 else None
            if not match:
                raise ValueError('Invalid synchronization configuration')
            values.append(match[1].lower())
        if values[0] != values[1]:
            raise ValueError('Firmware and server sync keys differ; update both explicitly.')
    else:
        data = dict(schema=2, key=secrets.token_hex(32), token=secrets.token_hex(32),
                    vault_id=secrets.token_hex(16), salt=secrets.token_hex(16))
        sync = secrets.token_hex(32)
        identity.parent.mkdir(parents=True, exist_ok=True)
        identity.write_text(json.dumps(data, indent=2)+'\n', encoding='utf-8')
        for path in configs:
            path.write_text('# Private deployment; do not commit.\nsync.key.hex='+sync+'\n', encoding='utf-8')
    settings = root/'firmware/vault-connection.json'
    if settings.is_file():
        saved = json.loads(settings.read_text(encoding='utf-8'))['url']
    else:
        saved = 'http://vault.local:8443'
    url = url or saved
    settings.write_text(json.dumps({'url':url}, indent=2)+'\n', encoding='utf-8')
    header = '#pragma once\n// Generated by tooling/init_config.py. Keep private.\n#include <cstdint>\nnamespace vault::builtin {\n'
    for name, field in [('Key','key'),('Id','vault_id'),('Salt','salt')]:
        header += 'inline constexpr uint8_t '+name+'[] = {' + ','.join('0x'+data[field][i:i+2] for i in range(0,len(data[field]),2)) + '};\n'
    header += 'inline constexpr char Token[] = '+json.dumps(data['token'])+';\n'
    header += 'inline constexpr char Url[] = '+json.dumps(url)+';\n}\n'
    (root/'firmware/main/core/vault_builtin.hpp').write_text(header, encoding='utf-8')
    print('Deployment initialized; existing keys preserved. Secret values omitted.')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--url', help='HTTP(S) server origin reachable from the device; standard port may be omitted')
    args=parser.parse_args()
    initialize(url=args.url)

if __name__=='__main__':
    main()
