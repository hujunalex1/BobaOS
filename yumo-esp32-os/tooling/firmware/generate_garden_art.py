"""Original Yumo pixel pets. Reproducible, dependency-free artwork; no external assets."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def sprite(route,rare=False,baby=False):
    p=[[0]*32 for _ in range(32)]
    def rect(x,y,w,h,c):
        for yy in range(max(0,y),min(32,y+h)):
            for xx in range(max(0,x),min(32,x+w)):p[yy][xx]=c
    def ellipse(cx,cy,rx,ry,c):
        for y in range(32):
            for x in range(32):
                if ((x-cx)/rx)**2+((y-cy)/ry)**2<=1:p[y][x]=c
    def poly(points,c):
        for y in range(32):
            for x in range(32):
                inside=False;j=len(points)-1
                for i,(xi,yi) in enumerate(points):
                    xj,yj=points[j]
                    if (yi>y)!=(yj>y) and x<(xj-xi)*(y-yi)/(yj-yi)+xi:inside=not inside
                    j=i
                if inside:p[y][x]=c
    def outlined(cx,cy,rx,ry,c=2):ellipse(cx,cy,rx,ry,1);ellipse(cx,cy,rx-1,ry-1,c)
    if baby:
        if route==0:
            outlined(16,21,9,10,2);rect(14,8,2,6,7);poly([(15,10),(9,7),(10,4),(17,7)],7);poly([(15,9),(19,4),(23,5),(20,9)],4)
        else:
            outlined(10,10,3,7);outlined(22,10,3,7);outlined(16,22,10,8);rect(13,13,7,3,4)
    else:
        if route==0: # leaf rabbit: soft ears and a botanical crown
            outlined(9,8,3,8);outlined(22,8,3,8);rect(9,4,1,8,4);rect(22,4,1,8,4)
        elif route==1: # guardian bear: round ears and a small amber shield
            outlined(7,12,5,5);outlined(25,12,5,5);rect(5,10,3,3,3);rect(24,10,3,3,3)
        elif route==2: # owl: cape wings and feather tufts
            poly([(5,13),(2,25),(11,27),(11,15)],1);poly([(26,13),(30,25),(22,27),(22,15)],1)
            poly([(5,16),(4,24),(10,25),(10,16)],3);poly([(26,16),(28,24),(23,25),(23,16)],3)
            poly([(8,12),(7,3),(14,10),(18,10),(25,3),(24,14)],1)
        elif route==3: # fox: pointed ears and a white-tipped tail
            poly([(21,23),(29,12),(31,16),(29,28),(23,29)],1);poly([(24,24),(29,15),(30,17),(28,26)],2);poly([(27,21),(29,15),(30,17),(29,22)],6)
            poly([(5,17),(6,2),(15,11),(19,11),(27,2),(26,18)],1);poly([(8,12),(8,5),(12,10)],4);poly([(22,11),(25,5),(24,14)],4)
        elif route==4: # songbird: curled crest and a fan tail
            poly([(10,24),(2,16),(3,26),(10,29)],1);poly([(10,24),(4,19),(5,25),(11,27)],8)
            rect(14,5,3,8,1);rect(16,3,7,3,1);rect(17,4,5,2,8)
        elif route==5: # moon spirit: floating fins and crescent halo
            ellipse(16,7,7,5,9);ellipse(18,5,6,4,0)
            poly([(7,18),(1,21),(7,25),(10,23)],1);poly([(25,18),(31,21),(25,25),(22,23)],1)
            poly([(4,21),(8,21),(8,24)],8);poly([(28,21),(24,21),(24,24)],8)
        outlined(16,21,11 if route==1 else 10,9)
        ellipse(16,24,8,5,3);ellipse(15,20,8,6,2);ellipse(13,16,5,2,4)
        if route==1:rect(11,26,10,3,9);rect(15,25,2,5,8)
        elif route==2:ellipse(11,19,4,4,4);ellipse(21,19,4,4,4);poly([(15,21),(18,21),(16,24)],9)
        elif route==3:poly([(7,21),(15,24),(17,24),(25,21),(22,28),(10,28)],4)
        elif route==4:poly([(23,18),(29,21),(24,23)],9)
        elif route==5:rect(10,29,3,2,2);rect(17,29,3,2,2);rect(23,27,2,3,2)
        if route!=5:rect(8,29,6,2,1);rect(19,29,6,2,1);rect(9,29,4,1,3);rect(20,29,4,1,3)
    # Shared facial language: lit eyes, blush, and a tiny smile.
    rect(10,18,3,4,1);rect(20,18,3,4,1);rect(10,18,1,1,6);rect(20,18,1,1,6)
    rect(7,22,4,2,5);rect(23,22,3,2,5);rect(15,23,1,1,1);rect(17,23,1,1,1);rect(16,24,1,1,1)
    if rare:
        for x,y in ((10,8),(16,5),(22,8)):
            rect(x-2,y,5,1,9);rect(x,y-2,1,5,9);rect(x,y,1,1,6)
        rect(13,10,7,2,8);rect(14,9,5,1,9)
    return p

def main():
    colors=[(0x96C79A,0x5C986C,0xD8EDB4,0xEBB761),(0xD8B181,0xA77D65,0xF4D8AC,0x769EB3),
            (0xB4B1DB,0x807FAD,0xE3DBEB,0xBFA966),(0xEFBB9B,0xCD8D78,0xFFE4BB,0x79C1BA),
            (0xF1A9BA,0xC982A3,0xFFE1DA,0x7BBBCB),(0x9BD8D2,0x64AEB5,0xE0F6E2,0xAA94CB)]
    images=[];palettes=[]
    for route in range(6):
        for rare in (False,True):
            images.append(sprite(route,rare));base,shade,light,accent=colors[route]
            if rare:base,light=light,0xFFF5D6
            palettes.append([0,0x374B50,base,shade,light,0xEEA7A2,0xFFFCEE,0x5C9B75,accent,0xEAC76E,0xE8A4CC,0x8CCCD0,0xA5BDB8,0x516578,0xEAA479,0xFAEDAD])
    for n in range(2):images.append(sprite(n,baby=True));palettes.append(palettes[0])
    out=['// Original pixel artwork, generated by tooling/firmware/generate_garden_art.py.','#pragma once','#include <cstdint>','namespace ui::garden_art {','inline constexpr unsigned Count=14,Size=32;','inline constexpr char Sprites[Count][Size*Size+1]={']
    for p in images:
        out+=['    '+('' if y else '')+'"'+''.join(format(v,'x') for v in row)+'"'+(',' if y==31 else '') for y,row in enumerate(p)]
    out+=['};','inline constexpr uint32_t Palettes[Count][16]={']
    out+=['    {'+','.join(f'0x{c:06x}' for c in p)+'},' for p in palettes]
    out+=['};','}']
    (ROOT/'firmware/main/ui/garden_art.hpp').write_text('\n'.join(out)+'\n',encoding='utf8')
    print('Generated 14 original 32x32 pixel sprites and palettes (12 adults, 2 young forms).')
if __name__=='__main__':main()
