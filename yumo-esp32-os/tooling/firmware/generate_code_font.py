"""Generate the small 13px ASCII monospace reader font (no firmware build)."""
from pathlib import Path
from update_menu_font import new_glyphs
from ttf2lvgl_emit import emit_c
ROOT=(Path(__file__).resolve().parents[2]/'firmware')
def main():
    glyphs=list(new_glyphs(range(32,127),13,'DejaVu Sans Mono'))
    for g in glyphs:
        g.adv_w=8*16
        assert g.box_h<=16
        g.ofs_y=max(-3,min(g.ofs_y,13-g.box_h))
    output=ROOT/'main/ui/lv_font_code_13.c'
    emit_c(str(output),'lv_font_code_13',13,2,glyphs,13,-3,16,deduplicate_bitmaps=True)
    s=output.read_text(encoding='utf-8').replace('/* Auto-generated by tools/ttf2lvgl.py. DO NOT EDIT. */','/* Generated from DejaVu Sans Mono by tools/generate_code_font.py.\n * License: knowledge/licenses/DejaVu.txt. ASCII, 13px, 8px fixed advance. */',1)
    output.write_text(s,encoding='utf-8',newline='\n');print('95 mono glyphs; 16px line height; no CJK font changes')
if __name__=='__main__':main()
