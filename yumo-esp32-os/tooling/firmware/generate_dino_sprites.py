"""Bake Chromium's indexed 1x runner sprite into small RGB565 LVGL images.

No runtime decoder, extra dependencies or network access. Input is Chromium
124.0.6367.91 components/neterror/resources/images/default_100_percent/offline.png.
The original BSD license is kept in main/third_party/chromium-LICENSE.
"""
from pathlib import Path
import struct, sys, zlib
ROOT=(Path(__file__).resolve().parents[2]/'firmware')

def strip_halo(pixels,w,h):
    # Only white pixels connected to the exterior are removed. Enclosed eyes
    # remain white; transparent background and the original dark silhouette stay.
    result=list(pixels);seen=set();queue=[]
    for y in range(h):
        for x in range(w):
            if x in (0,w-1) or y in (0,h-1):queue.append(y*w+x)
    while queue:
        i=queue.pop()
        if i in seen:continue
        seen.add(i);r,g,b,a=result[i]
        if a and min(r,g,b)<240:continue
        result[i]=(r,g,b,0)
        x,y=i%w,i//w
        if x:queue.append(i-1)
        if x+1<w:queue.append(i+1)
        if y:queue.append(i-w)
        if y+1<h:queue.append(i+w)
    return result

def png(path):
    data=path.read_bytes(); assert data[:8]==b'\x89PNG\r\n\x1a\n'
    pos=8; compressed=bytearray(); palette=[]; alpha=[]
    while pos<len(data):
        n=struct.unpack_from('>I',data,pos)[0]; tag=data[pos+4:pos+8]; value=data[pos+8:pos+8+n]; pos+=n+12
        if tag==b'IHDR': w,h,depth,color,comp,filt,inter=struct.unpack('>IIBBBBB',value)
        elif tag==b'PLTE': palette=[tuple(value[i:i+3]) for i in range(0,len(value),3)]
        elif tag==b'tRNS': alpha=list(value)
        elif tag==b'IDAT': compressed.extend(value)
    assert depth==4 and color==3 and comp==filt==inter==0
    raw=zlib.decompress(compressed); stride=(w+1)//2; prev=bytearray(stride); result=[]
    def paeth(a,b,c):
        p=a+b-c; pa,pb,pc=abs(p-a),abs(p-b),abs(p-c)
        return a if pa<=pb and pa<=pc else b if pb<=pc else c
    for y in range(h):
        mode=raw[y*(stride+1)]; row=bytearray(raw[y*(stride+1)+1:(y+1)*(stride+1)])
        assert mode in range(5)
        for i in range(stride):
            a=row[i-1] if i else 0; b=prev[i]; c=prev[i-1] if i else 0
            row[i]=(row[i]+(0,a,b,(a+b)//2,paeth(a,b,c))[mode])&255
        pixels=[]
        for x in range(w):
            index=(row[x//2]>>(4 if x%2==0 else 0))&15; opacity=alpha[index] if index<len(alpha) else 255
            pixels.append((*palette[index],opacity))
        result.append(pixels);prev=row
    return result

def main():
    src=png(Path(sys.argv[1]));out=['// Derived from Chromium 124 runner sprites, BSD-3-Clause. See third_party/chromium-LICENSE.',
        '// Generated by tools/generate_dino_sprites.py; static RGB565A8, no runtime decode.',
        '#pragma once','#include "lvgl.h"','namespace dino::sprites {']
    names=[]
    def sprite(name,x,y,sw,sh,w,h,double=False):
        values=[];opacity=[];pixels=[]
        for py in range(h):
            for px in range(w):
                if double and px==13: rgb=(255,255,255,0)
                else: rgb=src[y+py*sh//h][x+((px if not double else px if px<13 else px-14)*sw//(13 if double else w))]
                pixels.append(rgb)
        if name.startswith('Rex'):pixels=strip_halo(pixels,w,h)
        for r,g,b,a in pixels:
            value=((r>>3)<<11)|((g>>2)<<5)|(b>>3);values.extend((value&255,value>>8));opacity.append(a)
        values.extend(opacity) # separate alpha plane, so jumps do not erase the scenery
        out.append(f'alignas(4) inline constexpr uint8_t {name}Pixels[]={{')
        out.extend('    '+','.join(f'0x{v:02x}' for v in values[i:i+24])+',' for i in range(0,len(values),24));out.append('};')
        names.append((name,w,h))
    for i,offset in enumerate((0,88,132,220)):sprite('Rex'+str(i),848+offset,2,44,47,31,33)
    sprite('Cactus0',228,2,17,35,13,25);sprite('Cactus1',332,2,25,50,13,35);sprite('Cactus2',228,2,17,35,27,25,True)
    out+=['constexpr lv_image_dsc_t describe(const uint8_t *pixels,unsigned w,unsigned h) {',
        '    lv_image_dsc_t d{};d.header.magic=LV_IMAGE_HEADER_MAGIC;d.header.cf=LV_COLOR_FORMAT_RGB565A8;',
        '    d.header.w=w;d.header.h=h;d.header.stride=w*2;d.data_size=w*h*3;d.data=pixels;return d;','}']
    for group in ('Rex','Cactus'):
        out.append(f'inline constexpr lv_image_dsc_t {group}[]={{'+','.join(f'describe({name}Pixels,{w},{h})' for name,w,h in names if name.startswith(group))+'};')
    out.append('} // namespace dino::sprites\n')
    (ROOT/'main/apps/dino_sprites.hpp').write_text('\n'.join(out),encoding='utf-8')
    print('Baked',sum(w*h*3 for _,w,h in names),'bytes of RGB565A8 pixels')
if __name__=='__main__':main()
