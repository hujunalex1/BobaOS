"""Compile/run Java 8 course oracle, then build the bounded device lesson pack."""
from pathlib import Path
import argparse, hashlib, json, os, re, struct, subprocess, sys, zlib
ROOT=(Path(__file__).resolve().parents[2]/'firmware')
sys.path.insert(0,str(ROOT/'../resources/knowledge'))
sys.path.insert(0,str(ROOT/'../tooling'))
from environment import java_tool
from pattern_game import LESSONS

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--run-dir',type=Path,required=True)
    args=ap.parse_args();run=args.run_dir.resolve()
    assert run.is_relative_to((ROOT.parent/'artifacts/validation').resolve());run.mkdir(parents=True,exist_ok=False)
    java=java_tool()
    javac=java_tool('javac');out=run/'java';out.mkdir()
    source=ROOT/'../resources/knowledge/PatternExamples.java';raw=source.read_text(encoding='utf-8')
    commands=[[str(javac),'-encoding','UTF-8','-source','1.8','-target','1.8','-d',str(out),str(source),str(ROOT/'../resources/knowledge/PatternSemanticsTest.java')],
              [str(java),'-cp',str(out),'PatternSemanticsTest'],
              [str(java),'-cp',str(out),'PatternExamples']]
    for i,command in enumerate(commands):
        result=subprocess.run(command,cwd=ROOT,capture_output=True,timeout=60,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
        (run/f'java-{i}.log').write_bytes(result.stdout+result.stderr)
        if result.returncode:raise RuntimeError(result.stderr.decode(errors='replace'))
    records={}
    for line in result.stdout.decode('utf-8').splitlines():
        a,b,c,value,trace=line.split('\t');records[int(a),int(b),int(c)]=dict(output=value,trace=trace.split('|'))
    assert len(records)==26*2*3
    # Authored independently of Game.goal and Java EXPECTED: keep the two
    # implementations tied to the same observable mission contract.
    contract=json.loads((ROOT/'../tooling/firmware/fixtures/pattern_missions.json').read_text(encoding='utf-8'))
    assert len(contract)==78
    for case in contract:
        record=records[case['id'],0,case['stage']]
        assert record['output']==case['output'],case
        at=0
        for event in case.get('java_events',[]):
            at=record['trace'].index(event,at)+1
    snippets=dict(re.findall(r'// @(\S+)\n(.*?)(?=    // @)',raw,re.S))
    payload=[];lessons=[]
    for i,item in enumerate(LESSONS):
        lesson=dict(item);lesson['code']=snippets[item['id']].strip()
        lesson['runs']=[records[i,design,choice] for design in range(2) for choice in range(3)]
        for choice in range(3):assert lesson['runs'][choice]['output']==lesson['runs'][choice+3]['output']
        assert len({(x['output'],tuple(x['trace'])) for x in lesson['runs'][:3]})==3
        assert all(1<=len(x['trace'])<=12 for x in lesson['runs'])
        block=json.dumps(lesson,ensure_ascii=False,separators=(',',':')).encode('utf-8')
        assert len(block)<=24576
        payload.append(block);lessons.append(lesson)
    table=bytearray();offset=16+16*len(payload)
    for i,block in enumerate(payload):
        table+=struct.pack('<IIII',offset,len(block),zlib.crc32(block),i);offset+=len(block)
    header=b'YMPAT01\0'+struct.pack('<II',len(payload),zlib.crc32(table))
    package=header+table+b''.join(payload)
    sd=ROOT/'../resources/sdcard/patterns';sd.mkdir(parents=True,exist_ok=True)
    (sd/'lessons.ypg').write_bytes(package)
    metadata=ROOT.parent/'artifacts/resources/patterns';metadata.mkdir(parents=True,exist_ok=True)
    (metadata/'lessons.json').write_text(json.dumps(lessons,ensure_ascii=False,indent=2),encoding='utf-8')
    src=['// Generated by tools/build_pattern_game.py; Java oracle results, not a JVM.',
         '#include "pattern_format.hpp"','namespace core::patterns {',
         'const unsigned char Package[]={']
    src+=['    '+','.join(f'0x{v:02x}' for v in package[i:i+24])+',' for i in range(0,len(package),24)]
    src+=['};','const size_t PackageBytes=sizeof(Package);','const Catalog Catalogs[LessonCount]={']
    src += ['    {'+json.dumps(x['id'])+','+json.dumps(x['title'],ensure_ascii=False)+','+str(x['group'])+'},' for x in LESSONS]
    src+=['};','}']
    (ROOT/'main/core/pattern_data.cpp').write_text('\n'.join(src)+'\n',encoding='utf-8')
    summary=dict(passed=True,java_version='8',lessons=len(lessons),activities=len(lessons)*3,
        gof_patterns=len(lessons)-3,gof_activities=(len(lessons)-3)*3,executions=len(records),
        package_bytes=len(package),largest_lesson=max(map(len,payload)),
        package_sha256=hashlib.sha256(package).hexdigest(),source_sha256=hashlib.sha256(source.read_bytes()).hexdigest())
    (run/'result.json').write_text(json.dumps(summary,indent=2));print(json.dumps(summary))
if __name__=='__main__':main()
