# -*- coding: utf-8 -*-
# Generate a compact GBK -> Unicode mapping table as a C source file.
# GBK lead byte: 0x81-0xFE ; trail byte: 0x40-0x7E, 0x80-0xFE
# We emit one uint16 Unicode code point per (lead, trail) slot.
# Slot index = (lead - 0x81) * 190 + (trail_index)
#   trail_index = trail - 0x40         when 0x40..0x7E
#               = trail - 0x41         when 0x80..0xFE  (skip 0x7F)
# Table size = 126 * 190 = 23940 entries (uint16) = ~46.8 KB.

import codecs

LEAD_MIN, LEAD_MAX = 0x81, 0xFE
NLEAD = LEAD_MAX - LEAD_MIN + 1          # 126
NTRAIL = 190                              # 0x40..0x7E (63) + 0x80..0xFE (127)
SIZE = NLEAD * NTRAIL                     # 23940

table = [0] * SIZE

def trail_index(trail):
    if 0x40 <= trail <= 0x7E:
        return trail - 0x40
    if 0x80 <= trail <= 0xFE:
        return trail - 0x41
    return -1

for lead in range(LEAD_MIN, LEAD_MAX + 1):
    for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
        ti = trail_index(trail)
        if ti < 0:
            continue
        b = bytes([lead, trail])
        try:
            u = b.decode('gbk')
        except Exception:
            continue
        if len(u) != 1:
            continue
        cp = ord(u)
        if cp > 0xFFFF:
            cp = 0  # skip supplementary planes (rare in GBK)
        idx = (lead - LEAD_MIN) * NTRAIL + ti
        table[idx] = cp

with open('main/core/gbk_table.c', 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Auto-generated by tools/gen_gbk_table.py. Do not edit by hand.\n')
    f.write('// GBK double-byte -> Unicode BMP code point lookup table.\n')
    f.write('#include <stdint.h>\n\n')
    f.write('const uint16_t g_gbk_to_unicode[%d] = {\n' % SIZE)
    line = []
    for i, cp in enumerate(table):
        line.append('0x%04X' % cp)
        if len(line) == 16:
            f.write('    ' + ','.join(line) + ',\n')
            line = []
    if line:
        f.write('    ' + ','.join(line) + ',\n')
    f.write('};\n')
    f.write('const int g_gbk_table_size = %d;\n' % SIZE)
    f.write('const int g_gbk_nlead = %d;\n' % NLEAD)
    f.write('const int g_gbk_ntrail = %d;\n' % NTRAIL)

print('Wrote main/core/gbk_table.c with %d entries' % SIZE)