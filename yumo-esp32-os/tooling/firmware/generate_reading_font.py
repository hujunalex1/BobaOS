"""Generate a 15px/2bpp document font with exactly 20px line height.

Uses the installed Microsoft YaHei face, as the other baked Chinese fonts do.
Requires freetype-py. Only this reading font uses the compact line metrics;
the shared 16px UI font and its symbol fallback are unchanged.
"""
from pathlib import Path
import argparse, os
from ttf2lvgl import build_charset, render_glyphs
from ttf2lvgl_emit import emit_c

ROOT = (Path(__file__).resolve().parents[2]/'firmware')
LINE_HEIGHT = 20
BASELINE = 4

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', default=str(Path(os.environ['WINDIR'])/'Fonts/msyh.ttc'))
    parser.add_argument('--output', type=Path, default=ROOT/'main/ui/lv_font_reading_15.c')
    args = parser.parse_args()
    glyphs, _, _, _ = render_glyphs(args.font, 0, 15, 2, build_charset())
    adjusted = 0
    for glyph in glyphs:
        if not glyph.box_h:
            continue
        if glyph.box_h > LINE_HEIGHT:
            raise ValueError(f'U+{glyph.cp:04X} cannot fit a 20px line')
        # Hinting gives y/ý/ÿ an extra descender pixel. Move such glyphs only
        # as far as necessary; never cut or rescale their bitmap.
        old = glyph.ofs_y
        glyph.ofs_y = max(-BASELINE, min(old, LINE_HEIGHT-BASELINE-glyph.box_h))
        adjusted += glyph.ofs_y != old
        top = LINE_HEIGHT-BASELINE-glyph.box_h-glyph.ofs_y
        assert 0 <= top and top+glyph.box_h <= LINE_HEIGHT
    emit_c(str(args.output), 'lv_font_reading_15', 15, 2, glyphs,
           LINE_HEIGHT-BASELINE, -BASELINE, LINE_HEIGHT, deduplicate_bitmaps=True)
    source = args.output.read_text(encoding='utf8').replace(
        '/* Auto-generated by tools/ttf2lvgl.py. DO NOT EDIT. */',
        '/* Generated by tools/generate_reading_font.py. DO NOT EDIT. */\n'
        '/* Microsoft YaHei, 15px, 2bpp; 12 x 20px rows on the 240px panel. */', 1)
    args.output.write_text(source, encoding='utf8', newline='\n')
    print(f'{len(glyphs)} glyphs checked; {adjusted} vertical offsets fitted without clipping')

if __name__ == '__main__':
    main()
