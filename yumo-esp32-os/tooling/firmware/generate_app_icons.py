"""Original 1-bit launcher artwork; static 24/48px LVGL fonts, no heap or I/O."""
from pathlib import Path
import argparse,struct,zlib

ROOT=(Path(__file__).resolve().parents[2]/'firmware')
NAMES=('Fc','Programming','Dino','Maze','Patterns','Garden','Timer','Music','Xiaozhi')

def artwork():
    images=[]
    def canvas():return [[0]*24 for _ in range(24)]
    def rect(p,x,y,w,h,v=1):
        for row in range(y,y+h):
            for col in range(x,x+w):
                if 0<=col<24 and 0<=row<24:p[row][col]=v
    def line(p,a,b,width=2):
        x,y=a;ex,ey=b;dx=abs(ex-x);sx=1 if x<ex else -1
        dy=-abs(ey-y);sy=1 if y<ey else -1;error=dx+dy
        while True:
            rect(p,x,y,width,width)
            if (x,y)==(ex,ey):break
            step=2*error
            if step>=dy:error+=dy;x+=sx
            if step<=dx:error+=dx;y+=sy
    def disk(p,cx,cy,r,v=1):
        for y in range(24):
            for x in range(24):
                if (x-cx)**2+(y-cy)**2<=r*r:p[y][x]=v
    # Gamepad: curved grips, a direction cross, two separate action buttons.
    p=canvas();outline=[(5,5),(17,5),(20,7),(22,17),(20,19),(17,18),(14,15),(8,15),(5,18),(2,19),(0,17),(2,7),(5,5)]
    for a,b in zip(outline,outline[1:]):line(p,a,b)
    rect(p,5,8,2,7);rect(p,3,10,6,2);disk(p,16,9,1);disk(p,19,12,1)
    images.append(p)
    # Open reference book with separate code brackets on its two pages.
    p=canvas()
    for a,b in [((1,3),(8,3)),((8,3),(11,5)),((11,5),(14,3)),((14,3),(21,3)),
                ((1,3),(1,19)),((21,3),(21,19)),((1,19),(8,19)),
                ((8,19),(11,21)),((11,21),(14,19)),((14,19),(21,19)),((11,5),(11,20))]:line(p,a,b)
    for a,b in [((7,8),(4,11)),((4,11),(7,14)),((15,8),(18,11)),((18,11),(15,14))]:line(p,a,b)
    images.append(p)
    # Pixel dinosaur: square snout, eye, small arm, raised tail and two feet.
    p=canvas();rect(p,12,2,10,7);rect(p,11,7,8,8);rect(p,8,10,8,8)
    rect(p,5,12,7,4);rect(p,2,9,3,5);rect(p,1,6,2,5)
    rect(p,16,11,5,2);rect(p,19,12,2,3)
    rect(p,8,16,3,6);rect(p,9,21,4,1);rect(p,14,17,3,3);rect(p,16,19,3,2)
    rect(p,15,3,2,2,0);rect(p,19,7,3,2,0)
    images.append(p)
    # Maze corridor with a clearly separate ball in the lower-right chamber.
    p=canvas();rect(p,1,1,22,2);rect(p,1,1,2,22);rect(p,21,1,2,22)
    rect(p,1,21,13,2);rect(p,19,21,4,2)
    rect(p,6,2,2,6);rect(p,7,6,10,2);rect(p,11,7,2,6)
    rect(p,2,11,6,2);rect(p,6,11,2,7);rect(p,12,16,3,2)
    rect(p,17,7,2,5);disk(p,17,17,2)
    images.append(p)
    # Object collaboration: two upper modules connected to a lower module.
    p=canvas()
    for x,y in ((1,2),(15,2),(8,15)):
        rect(p,x,y,8,7);rect(p,x+2,y+2,4,3,0)
    line(p,(4,8),(4,11),1);line(p,(18,8),(18,11),1)
    line(p,(4,11),(18,11),1);line(p,(11,11),(11,15),2)
    images.append(p)
    # A smiling seedling: two leaves above a round pet, distinct from all other apps.
    p=canvas();disk(p,12,15,8);disk(p,12,15,6,0)
    disk(p,7,4,3);disk(p,16,3,3);line(p,(9,5),(12,9));line(p,(15,4),(12,9))
    rect(p,8,13,2,2);rect(p,15,13,2,2);rect(p,11,18,3,1)
    images.append(p)
    # Dedicated stopwatch: crown, shoulders, circular dial and elapsed hand.
    p=canvas();disk(p,12,14,9);disk(p,12,14,7,0)
    rect(p,9,0,7,2);rect(p,11,2,3,3)
    line(p,(3,5),(5,7),1);line(p,(19,5),(21,3),1)
