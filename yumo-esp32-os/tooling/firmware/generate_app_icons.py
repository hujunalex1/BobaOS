def scaled(p,scale):return [[p[y//scale][x//scale] for x in range(24*scale)] for y in range(24*scale)]
def packed(p):
    bits=[v for row in p for v in row]
    return bytes(sum(bits[i+j]<<(7-j) for j in range(8)) for i in range(0,len(bits),8))

def source():
    out=['/* Generated by tools/generate_app_icons.py. Original Yumo artwork. */', '#include "lvgl.h"', '']
    for size,height,base,offset in ((24,27,5,-2),(48,56,10,-4)):
        name=f'lv_font_app_icons_{size}';data=b''.join(packed(scaled(p,size//24)) for p in artwork())
        out.append(f'static LV_ATTRIBUTE_LARGE_CONST const uint8_t bitmap_{size}[] = {{')
        out += ['    '+', '.join(f'0x{b:02x}' for b in data[i:i+16])+',' for i in range(0,len(data),16)]
        out += ['};',f'static const lv_font_fmt_txt_glyph_dsc_t glyphs_{size}[] = {{',
                '    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},']
        for i,label in enumerate(NAMES):
            out.append(f'    {{.bitmap_index = {i*size*size//8}, .adv_w = {size*16}, .box_w = {size}, .box_h = {size}, .ofs_x = 0, .ofs_y = {offset}}}, /* {label}: U+{0xe000+i:04X} */')
        out += ['};',f'static const lv_font_fmt_txt_cmap_t cmaps_{size}[] = {{',
                f'    {{.range_start = 57344, .range_length = {len(NAMES)}, .glyph_id_start = 1,',
                '     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,',
                '     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},','};',
                f'static const lv_font_fmt_txt_dsc_t dsc_{size} = {{',
                f'    .glyph_bitmap = bitmap_{size}, .glyph_dsc = glyphs_{size}, .cmaps = cmaps_{size},',
                '    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 1,',
                '    .kern_classes = 0, .bitmap_format = 0, .stride = 0,','};',
                f'const lv_font_t {name} = {{',
                '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,',
                '    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
                f'    .line_height = {height}, .base_line = {base}, .subpx = LV_FONT_SUBPX_NONE,',
                '    .underline_position = -1, .underline_thickness = 1,',
                f'    .dsc = &dsc_{size}, .fallback = &lv_font_montserrat_{size}, .user_data = NULL,','};','']
    return '\n'.join(out)

def preview(path):
    # Actual 24px masks and their nearest-neighbour 48px forms on dark/light.
    width,height=96*len(NAMES),224;rows=[];pictures=artwork()
    for y in range(height):
        row=bytearray()
        for x in range(width):
            dark=y<112;local=y%112;picture=pictures[x//96]
            px,py=(x%96-24)//2,(local-32)//2
            on=0<=px<24 and 0<=py<24 and picture[py][px]
            row.extend((104,182,255) if dark and on else (35,99,180) if on else (20,24,30) if dark else (244,239,225))
        rows.append(b'\0'+row)
    def chunk(name,data):return struct.pack('>I',len(data))+name+data+struct.pack('>I',zlib.crc32(name+data))
    path.write_bytes(b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,height,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(b''.join(rows)))+chunk(b'IEND',b''))

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--preview',type=Path);a=ap.parse_args()
    (ROOT/'main/ui/lv_font_app_icons.c').write_text(source(),encoding='utf-8',newline='\n')
    if a.preview:a.preview.parent.mkdir(parents=True,exist_ok=True);preview(a.preview)
    print(f'{len(NAMES)} unique icons, 24/48px, {len(NAMES)*360} bitmap bytes; no runtime allocations')
